import {test,expect} from './fixtures.mjs';
import {login,uniqueLabel} from './helpers.mjs';
import {mkdir} from 'node:fs/promises';

test('fases 3–4: criar, reorganizar, excluir, salvar e reabrir seções do encaminhamento',async({page})=>{
  test.setTimeout(120000);
  await login(page);
  const mother=uniqueLabel('Mãe organização');
  await page.locator('[data-action="new-patient"]:visible').first().click();
  await page.locator('[name="motherName"]').fill(mother);
  await page.locator('[data-baby-field="name"]').first().fill(uniqueLabel('Bebê'));
  await page.locator('[name="consentData"]').check();
  const saved=page.waitForResponse(r=>r.url().endsWith('/api/clinical/patients')&&r.request().method()==='POST');
  await page.locator('[data-patient-form] button[type="submit"]:visible').first().click();
  const response=await saved;
  expect(response.status()).toBe(201);
  const patient=await response.json();
  await expect.poll(()=>page.evaluate(()=>Boolean(window.DeboraReferrals?.openNew))).toBe(true);
  await page.evaluate(id=>window.DeboraReferrals.openNew(id),patient.mother.id);
  await page.locator('[data-rf-new] button[type="submit"]').click();
  const editor=page.locator('[data-rf-editor]');
  await expect(editor).toBeVisible();
  await page.locator('[data-rf-new-section-title]').fill('Motivo da avaliação');
  await page.locator('[data-rf-add-section]').click();
  await expect(editor.locator('h2')).toHaveCount(1);
  await editor.locator('h2').first().fill('Motivo da avaliação');
  await editor.locator('h2').first().press('End');
  await page.locator('[data-rf-new-section-title]').fill('Condutas personalizadas');
  await page.locator('[data-rf-add-section]').click();
  await expect(page.locator('[data-rf-select-section] option')).toHaveCount(2);
  await page.locator('[data-rf-select-section]').selectOption('1');
  await page.locator('[data-rf-move-up]').click();
  await expect(editor.locator('h2').first()).toContainText('Condutas personalizadas');
  await page.locator('[data-rf-select-section]').selectOption('0');
  await page.locator('[data-rf-move-down]').click();
  await expect(editor.locator('h2').first()).toContainText('Motivo da avaliação');
  await page.locator('[data-rf-new-section-title]').fill('Remover este card');
  await page.locator('[data-rf-add-section]').click();
  await page.locator('[data-rf-select-section]').selectOption('2');
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('[data-rf-delete-section]').click();
  await expect(editor.locator('h2')).toHaveCount(2);
  await expect(editor).not.toContainText('Remover este card');
  await editor.locator('p').last().fill('Solicito avaliação e retorno profissional individualizado.');
  await mkdir('artifacts/referral-phase34',{recursive:true});
  await page.screenshot({path:'artifacts/referral-phase34/editor-desktop.png',fullPage:true,animations:'disabled'});
  await page.locator('[data-rf-save]').click();
  await expect(page.locator('.rf-layer')).toHaveCount(0);
  const rows=await page.evaluate(id=>window.DeboraDocuments.listDocuments(id,'referral'),patient.mother.id);
  const record=rows.find(x=>x.status==='draft'&&x.content?.html?.includes('Condutas personalizadas'));
  expect(record?.id).toBeTruthy();
  expect(record.content.html).toContain('Motivo da avaliação');
  expect(record.content.html).not.toContain('Remover este card');
  await page.evaluate(({id,doc})=>window.DeboraReferrals.openExisting(id,doc),{id:patient.mother.id,doc:record.id});
  await expect(page.locator('[data-rf-editor] h2')).toHaveCount(2);
  await expect(page.locator('[data-rf-editor]')).toContainText('Solicito avaliação e retorno profissional individualizado.');
});
