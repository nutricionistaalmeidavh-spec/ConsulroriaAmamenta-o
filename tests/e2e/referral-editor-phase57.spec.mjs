import {test,expect} from './fixtures.mjs';
import {login,authHeaders,uniqueLabel} from './helpers.mjs';
import {mkdir} from 'node:fs/promises';

test('fases 5–7: prévia fiel, alerta, salvamento, finalização congelada e API bloqueada',async({page})=>{
 test.setTimeout(150000);
 await login(page);
 const name=uniqueLabel('Mãe QA Encaminhamento Final');
 const baby=uniqueLabel('Bebê QA');
 await page.locator('[data-action="new-patient"]:visible').first().click();
 await page.locator('[name="motherName"]').fill(name);
 await page.locator('[data-baby-field="name"]').first().fill(baby);
 await page.locator('[name="consentData"]').check();
 const creation=page.waitForResponse(r=>r.url().endsWith('/api/clinical/patients')&&r.request().method()==='POST');
 await page.locator('[data-patient-form] button[type="submit"]:visible').first().click();
 expect((await creation).status()).toBe(201);
 const patient=await page.evaluate(()=>window.DeboraDocuments.patientContext());
 expect(patient?.mother?.id).toBeTruthy();
 await expect.poll(()=>page.evaluate(()=>Boolean(window.DeboraReferrals?.openNew))).toBe(true);
 await page.evaluate(id=>window.DeboraReferrals.openNew(id),patient.mother.id);
 await page.locator('[data-rf-new] button[type="submit"]').click();
 const editor=page.locator('[data-rf-editor]');
 await expect(editor).toBeVisible();
 const authored='<p>Prezado(a) colega,</p><h2>Queixa observada</h2><p>Relato clínico revisado individualmente pela consultora.</p><hr><p>Permaneço à disposição.</p>';
 await editor.evaluate((el,html)=>{el.innerHTML=html;el.dispatchEvent(new Event('input',{bubbles:true}))},authored);
 await page.locator('[data-rf-preview]').click();
 await expect(page.locator('[data-rf-preview-frame]')).toHaveAttribute('src',/^blob:/);
 await expect(page.locator('[data-rf-preview-review]')).toContainText('sem pendências');
 await mkdir('artifacts/referral-phase57',{recursive:true});
 await page.screenshot({path:'artifacts/referral-phase57/preview-desktop.png',fullPage:true,animations:'disabled'});
 await page.locator('[data-rf-preview-close]').click();
 await expect(page.locator('[data-rf-preview-layer]')).toHaveCount(0);
 await page.locator('[data-rf-save]').click();
 await expect(page.locator('.rf-layer')).toHaveCount(0);
 const rows=await page.evaluate(id=>window.DeboraDocuments.listDocuments(id,'referral'),patient.mother.id);
 const saved=rows.find(x=>x.status==='draft'&&x.content?.html?.includes('Queixa observada'));
 expect(saved?.id).toBeTruthy();
 expect(saved.content.html).toContain('<h2>Queixa observada</h2>');
 expect(saved.content.html).toContain('<hr>');
 await page.evaluate(({id,doc})=>window.DeboraReferrals.openExisting(id,doc),{id:patient.mother.id,doc:saved.id});
 await expect(editor).toContainText('Queixa observada');
 await editor.evaluate(el=>{el.innerHTML+='<p>[Descreva o motivo da avaliação.]</p>';el.dispatchEvent(new Event('input',{bubbles:true}))});
 await page.locator('[data-rf-finalize]').click();
 await expect(page.locator('[data-rf-preview-review]')).toContainText('Descreva o motivo da avaliação');
 await page.locator('[data-rf-preview-close]').click();
 const pending=await page.evaluate(id=>window.DeboraDocuments.listDocuments(id,'referral'),patient.mother.id);
 expect(pending.find(x=>x.id===saved.id)?.status).toBe('draft');
 await editor.evaluate(el=>{el.querySelector('p:last-child')?.remove();el.dispatchEvent(new Event('input',{bubbles:true}))});
 const dl=page.waitForEvent('download');
 await page.locator('[data-rf-finalize]').click();
 const downloaded=await dl;
 expect(downloaded.suggestedFilename()).toMatch(/encaminhamento.*\.pdf/i);
 const finals=await page.evaluate(id=>window.DeboraDocuments.listDocuments(id,'referral'),patient.mother.id);
 const record=finals.find(x=>x.id===saved.id);
 expect(record.status).toBe('finalized');
 expect(record.content.issued_snapshot.html).toContain('Queixa observada');
 const html=record.content.issued_snapshot.html;
 const patch=await page.request.patch('/api/clinical/records/clinical_documents?id=eq.'+encodeURIComponent(saved.id),{
   headers:await authHeaders(page),data:{status:'draft',content:{html:'<p>Adulterado</p>'}}
 });
 expect(patch.status()).toBe(409);
 const remove=await page.request.delete('/api/clinical/records/clinical_documents?id=eq.'+encodeURIComponent(saved.id),{headers:await authHeaders(page)});
 expect(remove.status()).toBe(409);
 const still=await page.evaluate(id=>window.DeboraDocuments.listDocuments(id,'referral'),patient.mother.id);
 expect(still.find(x=>x.id===saved.id).content.issued_snapshot.html).toBe(html);
 await page.evaluate(({id,doc})=>window.DeboraReferrals.openExisting(id,doc),{id:patient.mother.id,doc:saved.id});
 await expect(page.locator('[data-rf-editor]')).toHaveAttribute('contenteditable','false');
 await expect(page.locator('[data-rf-save]')).toHaveCount(0);
 await page.locator('[data-rf-preview]').click();
 await expect(page.locator('[data-rf-preview-frame]')).toHaveAttribute('src',/^blob:/);
 await page.screenshot({path:'artifacts/referral-phase57/finalized-preview.png',fullPage:true,animations:'disabled'});
});
